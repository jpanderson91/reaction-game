import os
import time

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def play_game_over(frames, score, get_key_func):
    i = 0
    while True:
        clear_screen()
        print(frames[i % len(frames)])
        print(f"\nFinal Score: {score}")
        print("\n[n] New Game    [q] Quit")
        key = get_key_func()
        if key == 'n':
            return 'new_game'
        if key == 'q':
            return 'quit'
        i += 1
        for _ in range(8):
            key = get_key_func()
            if key == 'n':
                return 'new_game'
            if key == 'q':
                return 'quit'



