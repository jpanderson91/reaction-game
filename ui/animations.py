import os
import time

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def play_game_over(frames, score, get_key_func):
    i = 0
    while True:
        clear_screen()
        print(frames[i % len(frames)])
        print(f"\nFinal Score: {score}")
        print("\n[n] New Game    [q] Quit")
        key = get_key_func()
        if key == 'n':
            return 'new_game'
        if key == 'q':
            return 'quit'
        i += 1
        for _ in range(8):
            key = get_key_func()
            if key == 'n':
                return 'new_game'
            if key == 'q':
                return 'quit'

def play_start_screen(frames, stats, get_key_func):
    i = 0
    while True:
        clear_screen()
        print(frames[i % len(frames)])
        # print stats if completed > 0
        if stats["completed"] > 0:
            print(f"Score            : {stats['score']}")
            print(f"Streak           : {stats['streak']}")
            print(f"Lives            : {stats['lives']}")
        if stats.get("highscores"):
            print("--- HIGH SCORES ---")
            for i, s in enumerate(stats["highscores"], 1):
                print(f"  {i}. {s}")

        print("Press Enter to start, or ESC to exit.")
        key = get_key_func()
        if key in ("\r", "\n"):
            return "play"
        if key and ord(key) == 27:
            return "exit"
        i += 1
        for _ in range(8):
            key = get_key_func()
            if key in ("\r", "\n"):
                return "play"
            if key and ord(key) == 27:
                return "exit"

def play_wait_screen(frames, duration, get_key_func):
    i = 0
    start = time.perf_counter()
    while (time.perf_counter() - start) < duration:
        clear_screen()
        print(frames[i % len(frames)])
        key = get_key_func()
        # check for ESC to cancel
        if key and ord(key) == 27:
            return "cancel"
        # delay loop
        i += 1
        for _ in range(8):
            key = get_key_func()
            if key and ord(key) == 27:
                return "cancel"
    return "done"

def play_result_screen(frames, message, get_key_func):
    i = 0
    while True:
        clear_screen()
        print(frames[i % len(frames)])
        print(f"\n{message}")
        print("\nPress any key to continue...")
        key = get_key_func()
        if key is not None:
            return
        i += 1
        for _ in range(8):
            key = get_key_func()
            if key is not None:
                return


